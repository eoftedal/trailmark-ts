#!/usr/bin/env node
// Fingerprint everything that determines per-file parse output, so cached
// parse results are invalidated automatically when any of it changes.
// Usage: node scripts/parser-fingerprint.mjs [--check]
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = "src/persist/parser-fingerprint.generated.ts";
const INPUTS = [
  "src/parsers",
  "src/models",
  "src/serialize.ts",
  "src/treesitter.ts",
  "grammars",
  "node_modules/web-tree-sitter/package.json",
];

function files(path) {
  const abs = join(root, path);
  if (statSync(abs).isFile()) return [path];
  return readdirSync(abs)
    .sort()
    .flatMap((name) => files(join(path, name)))
    .filter((f) => /\.(ts|wasm|json)$/.test(f));
}

export function fingerprint() {
  const hash = createHash("sha256");
  for (const file of INPUTS.flatMap(files)) {
    hash.update(relative(root, join(root, file)).replaceAll("\\", "/") + "\0");
    hash.update(readFileSync(join(root, file)));
    hash.update("\0");
  }
  return hash.digest("hex").slice(0, 16);
}

const source = (fp) => `// Generated by scripts/parser-fingerprint.mjs — do not edit.
/** Hash of parser sources, models and grammars; part of every parse-cache key. */
export const PARSER_FINGERPRINT = "${fp}";
`;

const fp = fingerprint();
const outPath = join(root, OUTPUT);
let current = "";
try {
  current = readFileSync(outPath, "utf8");
} catch {}
if (process.argv.includes("--check")) {
  if (current !== source(fp)) {
    console.error(`${OUTPUT} is stale; run: node scripts/parser-fingerprint.mjs`);
    process.exit(1);
  }
} else if (current !== source(fp)) {
  writeFileSync(outPath, source(fp));
  console.log(`parser fingerprint: ${fp}`);
}
